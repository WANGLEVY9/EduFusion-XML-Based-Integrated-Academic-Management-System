def generate_students(prefix: str, depts: list) -> list:
    """生成学生列表: [(id, name, gender, dept, password), ...]"""
    students = []
    seq = 1
    for dept_name, count in depts:
        for _ in range(count):
            sid = f"{prefix}{seq:03d}"
            gender = random.choice(['M', 'F'])
            name = random_name(gender)
            students.append((sid, name, gender, dept_name, '123456'))
            seq += 1
    return students

def generate_selections(students: list, course_list: list, groups: list, avg: int) -> list:
    """为每位学生生成选课: [(sid, cid), ...]"""
    all_cids = [c[0] for c in course_list]
    selections = []

    for sid, _, _, dept, _ in students:
        # 从每组中选若干门
        selected = set()
        for start, end, count in groups:
            pool = all_cids[start:end]
            random.shuffle(pool)
            k = min(count, len(pool))
            for cid in pool[:k]:
                selected.add(cid)

        # 额外随机加几门，增加差异化
        extra = avg - len(selected)
        if extra > 0:
            pool = [c for c in all_cids if c not in selected]
            random.shuffle(pool)
            for cid in pool[:extra]:
                selected.add(cid)

        for cid in selected:
            selections.append((sid, cid))

    return selections

