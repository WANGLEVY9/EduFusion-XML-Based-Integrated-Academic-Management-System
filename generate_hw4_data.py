def build_full_sql():
    lines = []

    lines.append("-- ============================================================")
    lines.append("-- EduFusion → hw4 数据上载脚本")
    lines.append("-- 组号: 2 | 生成时间: 自动生成")
    lines.append("-- ============================================================")
    lines.append("")
    lines.append(f"CREATE DATABASE IF NOT EXISTS hw4 CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;")
    lines.append("USE hw4;")
    lines.append("")

    # ── 建表 ──
    lines.append("-- ============================================================")
    lines.append("-- 建表: student")
    lines.append("-- ============================================================")
    lines.append("DROP TABLE IF EXISTS sc;")
    lines.append("DROP TABLE IF EXISTS course;")
    lines.append("DROP TABLE IF EXISTS student;")
    lines.append("""
CREATE TABLE IF NOT EXISTS student (
    student_id   VARCHAR(12) PRIMARY KEY,
    student_name VARCHAR(10) NOT NULL,
    gender       VARCHAR(2),
    department   VARCHAR(16),
    account      VARCHAR(10),
    password     VARCHAR(6),
    group_no     VARCHAR(10) DEFAULT '2',
    dept_no      VARCHAR(10)
);
""".strip())
    lines.append("")

    lines.append("""
CREATE TABLE IF NOT EXISTS course (
    course_id      VARCHAR(8) PRIMARY KEY,
    course_name    VARCHAR(16) NOT NULL,
    credit         VARCHAR(2),
    teacher_name   VARCHAR(20),
    location       VARCHAR(20),
    share_flag     CHAR(1),
    class_hours    VARCHAR(10),
    practice_hours VARCHAR(10),
    group_no       VARCHAR(10) DEFAULT '2',
    dept_no        VARCHAR(10)
);
""".strip())
    lines.append("")

    lines.append("""
CREATE TABLE IF NOT EXISTS sc (
    course_id  VARCHAR(8),
    student_id VARCHAR(12),
    score      VARCHAR(3),
    group_no   VARCHAR(10) DEFAULT '2',
    dept_no    VARCHAR(10),
    PRIMARY KEY (course_id, student_id)
);
""".strip())
    lines.append("")

    # ── 插入数据 ──
    all_students_sql = []
    all_courses_sql = []
    all_sc_sql = []

    for college_code, cfg in COLLEGES.items():
        dept_no = cfg['dept_no']
        prefix = cfg['student_prefix']
        course_list = cfg['course_list']
        depts = cfg['depts']
        groups = cfg['selection_groups']
        avg = cfg['avg_selections']

        # 生成数据
        students = generate_students(prefix, depts)
        selections = generate_selections(students, course_list, groups, avg)

        # student INSERT
        for sid, sname, gender, dept, pw in students:
            account = sid  # 用学号作为账号
            all_students_sql.append(
                f"('{sid}','{sname}','{gender}','{dept}','{account}','{pw}','{GROUP_NO}','{dept_no}')"
            )

        # course INSERT
        for cid, cname, credit, teacher, room, share in course_list:
            ch, ph = pick_hours(credit)
            all_courses_sql.append(
                f"('{cid}','{cname}','{credit}','{teacher}','{room}','{share}','{ch}','{ph}','{GROUP_NO}','{dept_no}')"
            )

        # sc INSERT
        for sid, cid in selections:
            all_sc_sql.append(
                f"('{cid}','{sid}',NULL,'{GROUP_NO}','{dept_no}')"
            )

        print(f"  [{college_code}] 学生: {len(students)}, 课程: {len(course_list)}, 选课: {len(selections)}")

    # 批量写入
    lines.append("-- ============================================================")
    lines.append("-- 学生数据 (3学院)")
    lines.append("-- ============================================================")
    # 分批写入，避免单条过长
    BATCH = 100
    for i in range(0, len(all_students_sql), BATCH):
        batch = all_students_sql[i:i+BATCH]
        lines.append("INSERT INTO student(student_id, student_name, gender, department, account, password, group_no, dept_no) VALUES")
        lines.append(",\n".join(batch) + ";")

    lines.append("")
    lines.append("-- ============================================================")
    lines.append("-- 课程数据 (3学院)")
    lines.append("-- ============================================================")
    for i in range(0, len(all_courses_sql), BATCH):
        batch = all_courses_sql[i:i+BATCH]
        lines.append("INSERT INTO course(course_id, course_name, credit, teacher_name, location, share_flag, class_hours, practice_hours, group_no, dept_no) VALUES")
        lines.append(",\n".join(batch) + ";")

    lines.append("")
    lines.append("-- ============================================================")
    lines.append("-- 选课数据 (3学院)")
    lines.append("-- ============================================================")
    for i in range(0, len(all_sc_sql), BATCH):
        batch = all_sc_sql[i:i+BATCH]
        lines.append("INSERT INTO sc(course_id, student_id, score, group_no, dept_no) VALUES")
        lines.append(",\n".join(batch) + ";")

    lines.append("")
    lines.append("-- ============================================================")
    lines.append("-- 完成!")
    lines.append("-- ============================================================")
    lines.append("SELECT CONCAT('Students: ', COUNT(*)) AS result FROM student;")
    lines.append("SELECT CONCAT('Courses: ', COUNT(*)) AS result FROM course;")
    lines.append("SELECT CONCAT('Selections: ', COUNT(*)) AS result FROM sc;")

    return "\n".join(lines)


