def generate_students(prefix, depts, dept_no):
    students = []
    seq = 1
    for dept_name, count in depts:
        for _ in range(count):
            sid = f"{prefix}{seq:03d}"
            gender = random.choice(['M', 'F'])
            name = random_name(gender)
            students.append((sid, name, gender, dept_name, sid, '123456', dept_no))
            seq += 1
    return students

def generate_selections(students, course_list, groups, avg):
    all_cids = [c[0] for c in course_list]
    selections = []
    for sid, *_ in students:
        selected = set()
        for start, end, count in groups:
            pool = all_cids[start:end]
            random.shuffle(pool)
            k = min(count, len(pool))
            for cid in pool[:k]:
                selected.add(cid)
        extra = avg - len(selected)
        if extra > 0:
            pool = [c for c in all_cids if c not in selected]
            random.shuffle(pool)
            for cid in pool[:extra]:
                selected.add(cid)
        for cid in selected:
            selections.append((sid, cid, generate_score()))
    return selections

